-- The Node server uses the service-role key and bypasses RLS.
-- No public policies are required for this server-side integration.

create table if not exists public.patients (
  id text primary key,
  data jsonb not null,
  created_at timestamptz not null default now(),
  status text not null default 'waiting',
  priority text not null default 'Normal'
);

create index if not exists patients_created_at_idx on public.patients (created_at desc);
create index if not exists patients_status_idx on public.patients (status);

alter table public.patients enable row level security;
grant select, insert, update, delete on public.patients to service_role;

create table if not exists public.calls (
  id bigint generated by default as identity primary key,
  patient_id text not null,
  room text not null,
  called_at timestamptz not null default now()
);

create index if not exists calls_called_at_idx on public.calls (called_at desc);

alter table public.calls enable row level security;
grant select, insert, delete on public.calls to service_role;
grant usage, select on sequence public.calls_id_seq to service_role;

create or replace function public.call_patient(p_patient_id text, p_room text, p_called_at timestamptz)
returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  updated_patient jsonb;
begin
  update public.patients
  set data = data || jsonb_build_object(
        'status', 'in_service',
        'calledAt', p_called_at,
        'room', p_room
      ),
      status = 'in_service'
  where id = p_patient_id
  returning data into updated_patient;

  if not found then
    return null;
  end if;

  insert into public.calls (patient_id, room, called_at)
  values (p_patient_id, p_room, p_called_at);

  return updated_patient;
end;
$$;

revoke all on function public.call_patient(text, text, timestamptz) from public, anon, authenticated;
grant execute on function public.call_patient(text, text, timestamptz) to service_role;

