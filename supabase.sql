create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  patient_id text not null,
  patient_name text not null,
  patient_dob text not null default '',
  patient_gender text not null default '',
  patient_phone text not null default '',
  patient_email text not null default '',
  patient_insurance text not null default '',
  patient_address text not null default '',
  patient_priority text not null default 'Normal',
  patient_notes text not null default '',
  room text not null default '',
  doctor text not null,
  specialty text not null,
  datetime timestamptz not null,
  arrival_time text not null default '',
  status text not null default 'scheduled',
  created_at timestamptz not null default now()
);

create index if not exists appointments_datetime_idx on public.appointments (datetime);

alter table public.appointments enable row level security;

alter table public.appointments add column if not exists patient_dob text not null default '';
alter table public.appointments add column if not exists patient_gender text not null default '';
alter table public.appointments add column if not exists patient_phone text not null default '';
alter table public.appointments add column if not exists patient_email text not null default '';
alter table public.appointments add column if not exists patient_insurance text not null default '';
alter table public.appointments add column if not exists patient_address text not null default '';
alter table public.appointments add column if not exists patient_priority text not null default 'Normal';
alter table public.appointments add column if not exists patient_notes text not null default '';
alter table public.appointments add column if not exists room text not null default '';

